/**
 * Builds `src/data/sample-photo.ts`: the neutral avatar shown until someone adds their own photo.
 * It is a head-and-shoulders silhouette on a soft gradient, drawn with 4 x 4 supersampling for smooth edges.
 *
 * Run: pnpm --filter @signature-studio/engine data:photo [--check]
 * - --check: compare the source and decompressed PNG content with the committed file.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dataURL, type Picture, png, pngContent } from './lib/png.ts';

type Rgb = readonly [number, number, number];

const SIZE = 320;
const SS = 4;
const FILE = fileURLToPath(new URL('../src/data/sample-photo.ts', import.meta.url));

const TOP_LEFT: Rgb = [0x4f, 0x8f, 0xd6];
const BOTTOM_RIGHT: Rgb = [0x7b, 0x61, 0xc9];
const HEAD: Rgb = [0xf4, 0xf7, 0xfb];
const BODY: Rgb = [0xe2, 0xea, 0xf5];

const mix = (a: Rgb, b: Rgb, t: number): Rgb => [
  a[0] + (b[0] - a[0]) * t,
  a[1] + (b[1] - a[1]) * t,
  a[2] + (b[2] - a[2]) * t,
];

/** Whether a point is inside the head (circle), the neck (rounded bar) or the shoulders (ellipse). */
function head(x: number, y: number): boolean {
  return (x - 160) ** 2 + (y - 130) ** 2 <= 64 ** 2;
}
function body(x: number, y: number): boolean {
  const neck = x >= 134 && x <= 186 && y >= 180 && y <= 236;
  const shoulders = ((x - 160) / 142) ** 2 + ((y - 334) / 112) ** 2 <= 1;
  return neck || shoulders;
}

function draw(): Picture {
  const px = new Uint8Array(SIZE * SIZE * 3);
  for (let y = 0; y < SIZE; y++)
    for (let x = 0; x < SIZE; x++) {
      let r = 0;
      let g = 0;
      let b = 0;
      for (let sy = 0; sy < SS; sy++)
        for (let sx = 0; sx < SS; sx++) {
          const fx = x + (sx + 0.5) / SS;
          const fy = y + (sy + 0.5) / SS;
          /* the background lightens a little behind the head */
          const glow = Math.max(0, 1 - Math.hypot(fx - 160, fy - 130) / 220) * 0.18;
          const base = mix(mix(TOP_LEFT, BOTTOM_RIGHT, (fx + fy) / (2 * SIZE)), [255, 255, 255], glow);
          const c = head(fx, fy) ? HEAD : body(fx, fy) ? BODY : base;
          r += c[0];
          g += c[1];
          b += c[2];
        }
      const i = (y * SIZE + x) * 3;
      const n = SS * SS;
      px[i] = Math.round(r / n);
      px[i + 1] = Math.round(g / n);
      px[i + 2] = Math.round(b / n);
    }
  return { w: SIZE, h: SIZE, px };
}

function content(source: string): string {
  return source.replace(/data:image\/png;base64,([A-Za-z0-9+/=]+)/g, (_url: string, base64: string) =>
    dataURL('image/png', pngContent(Buffer.from(base64, 'base64'))),
  );
}

function main(): void {
  const url = dataURL('image/png', png(draw()));
  const text = `/* Generated by scripts/build-sample-photo.ts. A neutral avatar, not a real person. */\nexport const SAMPLE_PHOTO =\n  '${url}';\n`;
  if (process.argv.includes('--check')) {
    const same = content(readFileSync(FILE, 'utf8')) === content(text);
    console.log(
      same ? 'sample-photo.ts is up to date.' : 'sample-photo.ts differs from the generator. Run data:photo.',
    );
    process.exitCode = same ? 0 : 1;
    return;
  }
  writeFileSync(FILE, text);
  console.log(`Wrote ${FILE} (${Math.round(text.length / 1024)} KB).`);
}

main();
